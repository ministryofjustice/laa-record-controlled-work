/**
 * Escapes plain text for embedding in HTML markup.
 * @param value Plain text to escape.
 * @returns HTML-escaped text.
 */
export function escapeHtml(value: string): string {
  return value
    .replaceAll("&", "&amp;")
    .replaceAll("<", "&lt;")
    .replaceAll(">", "&gt;")
    .replaceAll('"', "&quot;")
    .replaceAll("'", "&#39;");
}
